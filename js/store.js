  // 省市级联控件：省份下拉 + 城市下拉（省份变化自动联动城市并触发城市 change）
  // opts: { id: 城市select的id, onCity: 城市change内联脚本, attrs: 城市select附加属性 }
  function cityCascadeHTML(city, cls, opts) {
    opts = opts || {};
    const c = CITIES[city] ? city : getCity();
    const prov = getProvinceOfCity(c);
    const provOpts = Object.keys(PROVINCES).map(p => `<option ${p===prov?'selected':''}>${p}</option>`).join('');
    const cityOpts = PROVINCES[prov].map(cc => `<option ${cc===c?'selected':''}>${cc}</option>`).join('');
    const provCls = cls ? `${cls}-prov` : 'cascade-prov';
    const cityCls = cls ? `${cls}-city` : 'cascade-city';
    return `<select class="cascade-prov ${provCls}" onchange="Store.onProvChange(this)">${provOpts}</select>
      <select class="cascade-city ${cityCls}"${opts.id?` id="${opts.id}"`:''}${opts.onCity?` onchange="${opts.onCity}"`:''}${opts.attrs||''}>${cityOpts}</select>`;
  }
  // 省份变化 → 联动重绘同组城市下拉，并派发 change 触发模块联动
  function onProvChange(provSel) {
    const group = provSel.closest('.cascade-group') || provSel.parentElement;
    const citySel = group.querySelector('.cascade-city');
    if (!citySel) return;
    citySel.innerHTML = (PROVINCES[provSel.value]||[]).map(c => `<option>${c}</option>`).join('');
    citySel.dispatchEvent(new Event('change'));
  }

